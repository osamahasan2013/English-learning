import { z } from "zod";
import { traceStrokesSchema } from "@/lib/learning/tracing";
import { rubricCriteriaSchema } from "@/lib/learning/writing";

// The contract between stored content and the activity renderers. `questions.content`
// and `questions.answer` are JSON in the database; these schemas validate them on import
// (scripts/content/import.ts) and again when a lesson is loaded, so a malformed question
// is skipped and reported instead of breaking a child's lesson.
//
// Adding a question type = add its schema here, a row in activity_types, an evaluator
// branch in src/lib/learning/evaluate.ts and a renderer in src/features/activities.

const text = (max: number) => z.string().trim().min(1).max(max);

export const choiceOptionSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]{1,40}$/),
  // Up to a short sentence ("Which sentence makes sense?").
  text: z.string().trim().max(80).optional(),
  emoji: z.string().max(16).optional(),
  // What to say when the option's speaker is tapped (defaults to `text`).
  speech: z.string().trim().max(120).optional(),
});

export const introContentSchema = z.object({
  heading: text(80),
  body: z.string().trim().max(400).default(""),
  speech: z.string().trim().max(400).default(""),
  display: z.string().trim().max(40).optional(),
  examples: z
    .array(
      z.object({
        text: text(40),
        emoji: z.string().max(16).optional(),
        // Letters to highlight inside `text`, e.g. "sh" in "ship".
        highlight: z.string().max(8).optional(),
      }),
    )
    .max(8)
    .default([]),
  // Letters only: the letter's NAME and its SOUND, shown and played as two different
  // things ("bee" is the name; /b/ "buh" is the sound).
  letter: z
    .object({
      upper: z.string().trim().min(1).max(2),
      lower: z.string().trim().min(1).max(2),
      name: text(20),
      nameSpeech: text(40),
      soundLabel: text(8),
      soundSpeech: text(40),
    })
    .optional(),
});

export const choiceContentSchema = z.object({
  // Shown above the options: a letter, a word, or a short passage to read.
  display: z.string().trim().max(300).optional(),
  // Hide option labels so the child must rely on the picture/sound (listen-and-choose).
  hideOptionText: z.boolean().default(false),
  options: z.array(choiceOptionSchema).min(2).max(6),
});

// Spelling (Phase 6): a word's grapheme split as the spelling engine sees it (ship =
// sh·i·p with each grapheme's phonemes and phonics pattern), progressive hints, and the
// positions of a word's irregular part. Generated by the templates from the word bank.
export const spellingSegmentSchema = z.object({
  grapheme: z.string().regex(/^[a-z']{1,6}$/),
  phonemes: z.array(z.string().regex(/^[A-Z]{1,3}$/)).max(4).optional(),
  patternCode: z.string().max(40).nullable().optional(),
  patternType: z.string().max(40).nullable().optional(),
});
export const spellingHintSchema = z.object({
  kind: z.enum(["listen", "listen_slow", "sounds", "first_sound", "letters", "pattern", "tricky", "custom"]),
  text: text(120),
  speech: z.string().trim().max(160).default(""),
  // What to show with the hint ("sh _ _").
  show: z.string().trim().max(60).optional(),
});
const spellingSplit = z.array(spellingSegmentSchema).min(1).max(16).optional();
const spellingHints = z.array(spellingHintSchema).max(4).default([]);
// A sound the child can tap to hear (a phoneme label such as "sh", never the letters).
const heardSoundSchema = z.object({ label: text(8), sayAs: text(40) });

export const missingLetterContentSchema = z
  .object({
    word: text(40),
    emoji: z.string().max(16).optional(),
    // "sound": the missing part is a sound (MISSING_SOUND) — its sound can be played.
    mode: z.enum(["letter", "sound"]).default("letter"),
    sound: heardSoundSchema.optional(),
    split: spellingSplit,
    hints: spellingHints,
    parts: z
      .array(z.union([z.object({ text: text(20) }), z.object({ blank: z.literal(true) })]))
      .min(2)
      .max(8),
    choices: z.array(text(8)).min(2).max(6),
  })
  .refine((c) => c.parts.filter((p) => "blank" in p).length === 1, {
    message: "missing-letter content needs exactly one blank part",
  });

export const wordBuilderContentSchema = z.object({
  emoji: z.string().max(16).optional(),
  // What to say as the target word (defaults to the accepted answer).
  speech: z.string().trim().max(60).optional(),
  tiles: z.array(text(8)).min(2).max(12),
  slots: z.number().int().min(1).max(10),
  // Show the tiles joined slowly (C → A → T → CAT) before building.
  demonstrateBlend: z.boolean().default(false),
  // "scrambled": the tiles are the word's own letters, mixed up (SCRAMBLED_WORD).
  mode: z.enum(["build", "scrambled"]).default("build"),
  split: spellingSplit,
  hints: spellingHints,
});

export const sentenceBuilderContentSchema = z.object({
  emoji: z.string().max(16).optional(),
  tokens: z.array(text(24)).min(2).max(14),
});

// Type a word: listen and type (picture + word), dictation (the word only, limited
// replays), sounds to word (tap the sounds, then write the word they make), and the
// writing modes: copy (the word is shown; WORD_COPY), picture (the picture first, the word
// only on request; IMAGE_TO_WORD) and grapheme (hear a sound, write the letter or letters
// that spell it; SOUND_TO_LETTER — every accepted spelling of the sound is an answer).
export const spellingContentSchema = z.object({
  emoji: z.string().max(16).optional(),
  speech: z.string().trim().max(60).optional(),
  hint: z.string().trim().max(120).optional(),
  mode: z.enum(["listen", "dictation", "sounds", "copy", "picture", "grapheme"]).default("listen"),
  sounds: z.array(heardSoundSchema).min(1).max(10).optional(),
  // Letters for tile input (the word's letters plus a few others).
  tiles: z.array(text(6)).min(2).max(16).optional(),
  split: spellingSplit,
  // Grapheme positions of the word's irregular part ("ai" in said = [1]).
  irregular: z.array(z.number().int().min(0).max(15)).max(6).default([]),
  hints: spellingHints,
});

// Hear a sentence, write it. Checked word by word; capitals and the end mark only when
// the answer asks for them (requirePunctuation).
export const sentenceDictationContentSchema = z.object({
  emoji: z.string().max(16).optional(),
  speech: text(200),
  wordCount: z.number().int().min(1).max(20),
  hints: spellingHints,
});

const itemId = z.string().regex(/^[a-z0-9-]{1,40}$/);

// Match pairs (left ↔ right): a picture to its word, a capital to its small letter.
export const matchItemSchema = z.object({
  id: itemId,
  // A word, or a child-friendly meaning (word → meaning matching).
  text: z.string().trim().max(80).optional(),
  emoji: z.string().max(16).optional(),
  speech: z.string().trim().max(120).optional(),
});
export const matchContentSchema = z.object({
  left: z.array(matchItemSchema).min(2).max(6),
  right: z.array(matchItemSchema).min(2).max(6),
});

// Sort items into 2–4 groups ("sh" words / "ch" words).
export const sortContentSchema = z.object({
  groups: z
    .array(z.object({ id: itemId, label: text(40), emoji: z.string().max(16).optional() }))
    .min(2)
    .max(4),
  items: z.array(matchItemSchema).min(2).max(10),
});

// Drag words from a bank into the blanks of a sentence or word ("The ___ sat.").
export const dragDropContentSchema = z
  .object({
    emoji: z.string().max(16).optional(),
    parts: z
      .array(z.union([z.object({ text: text(60) }), z.object({ blank: z.literal(true) })]))
      .min(2)
      .max(12),
    bank: z.array(text(24)).min(2).max(8),
  })
  .refine((c) => c.parts.some((p) => "blank" in p), { message: "drag-drop content needs a blank" });

// Reading comprehension: the passage lives in the activity config (a story, shared by its
// questions); each question is a choice about it — multiple choice, true/false (two options
// "yes"/"no") or a word's meaning in the text. `ref` points at the sentence that answers it
// (paragraph and sentence index), highlighted after answering so the child can look back.
export const passageRefSchema = z.object({
  paragraph: z.number().int().min(0).max(40),
  sentence: z.number().int().min(0).max(40),
});
export const readingContentSchema = choiceContentSchema.extend({
  format: z.enum(["choice", "true_false", "word_meaning"]).default("choice"),
  // The word asked about in a word-meaning question (highlighted in the text).
  focusWord: z.string().trim().max(40).optional(),
  ref: passageRefSchema.optional(),
});

// Choose every right answer ("Which animals were in the story?"). Two or more are right.
export const selectAllContentSchema = choiceContentSchema.extend({
  options: z.array(choiceOptionSchema).min(3).max(6),
  ref: passageRefSchema.optional(),
});

// Put the events of a story in order. Events are shown in the stored order (shuffled by
// the importer so they never start in the right order).
export const orderEventsContentSchema = z.object({
  events: z
    .array(z.object({ id: itemId, text: text(120), emoji: z.string().max(16).optional() }))
    .min(3)
    .max(6),
});

// Read a text (the story in the activity config): listen first or read first, tap a word
// to hear it, re-read. Unscored; the device reports a reading session instead.
export const readPassageContentSchema = z.object({
  mode: z.enum(["listen_first", "read_first", "reread"]).default("read_first"),
  // Highlight each word (youngest) or each sentence while the text is read aloud.
  highlight: z.enum(["word", "sentence"]).default("sentence"),
  // Asked after reading, as the child's own check ("How was that?"). Never scored.
  selfCheck: z.boolean().default(true),
});

// Write a word or finish a sentence, with a word bank to copy from.
export const writingContentSchema = z.object({
  emoji: z.string().max(16).optional(),
  starter: z.string().trim().max(80).optional(),
  wordBank: z.array(text(24)).min(2).max(8),
  hint: z.string().trim().max(120).optional(),
});

// Handwriting with a finger, mouse or pen (tracing.ts). `glyph` names the reference
// handwriting (handwriting_glyphs.code); the lesson loader sends its strokes with the step.
//   trace — the letter is drawn faintly and the child goes over it (TRACING)
//   copy  — the model is shown beside an empty box with guide lines (LETTER_WRITING)
//   write — the child hears the letter (its name, its sound, or a word that starts with it)
//           and writes it from memory (LETTER_WRITING, SOUND_TO_LETTER)
export const tracingContentSchema = z.object({
  glyph: z.string().regex(/^[a-z0-9-]{2,60}$/),
  mode: z.enum(["trace", "copy", "write"]).default("trace"),
  // What is said: "Trace small a." / a speech token for a sound ({/M/}).
  speech: z.string().trim().max(120).optional(),
  // Show where to start (a dot) and the stroke arrows.
  showStart: z.boolean().default(true),
});

// Typed writing (writing.ts). A sentence: copy one (the model is shown; SENTENCE_COPY),
// finish one (one blank; SENTENCE_COMPLETION) or write one freely about a picture or a
// prompt (SENTENCE_WRITING, judged by a rubric, never by matching a stored sentence).
export const sentenceWritingContentSchema = z
  .object({
    mode: z.enum(["copy", "complete", "free"]),
    emoji: z.string().max(16).optional(),
    model: z.string().trim().min(1).max(200).optional(),
    parts: z
      .array(z.union([z.object({ text: text(120) }), z.object({ blank: z.literal(true) })]))
      .min(2)
      .max(8)
      .optional(),
    // Words to help (tap to hear, copy); free writing only.
    wordBank: z.array(text(24)).max(12).default([]),
    starter: z.string().trim().max(80).optional(),
    hint: z.string().trim().max(160).optional(),
  })
  .superRefine((c, ctx) => {
    if (c.mode === "copy" && !c.model) ctx.addIssue({ code: "custom", message: "copying needs the model sentence" });
    if (c.mode === "complete" && (c.parts?.filter((p) => "blank" in p).length ?? 0) !== 1)
      ctx.addIssue({ code: "custom", message: "finishing a sentence needs exactly one blank" });
  });

// Guided and paragraph writing: a topic, a picture, boxes to write in (frames with sentence
// starters, or the parts of a paragraph: topic sentence, details, ending), a word bank and
// a short checklist. Scaffolding shrinks with the level (layout "free" is one box).
export const guidedWritingContentSchema = z.object({
  layout: z.enum(["frames", "paragraph", "free"]),
  topic: text(120),
  emoji: z.string().max(16).optional(),
  frames: z
    .array(
      z.object({
        label: z.string().trim().max(40).optional(),
        starter: z.string().trim().max(80).optional(),
        placeholder: z.string().trim().max(80).optional(),
      }),
    )
    .min(1)
    .max(8),
  wordBank: z.array(text(24)).max(16).default([]),
  checklist: z.array(text(80)).max(6).default([]),
});

// Story sequence writing: put pictures of a story in order, then write a sentence for each
// (and, at Grade 2, join them with sequence words). The story itself comes from the
// activity config (config.story), as for reading questions.
export const storyOrderWritingContentSchema = z.object({
  events: z
    .array(z.object({ id: z.string().regex(/^[a-z0-9-]{1,40}$/), emoji: text(16), label: z.string().trim().max(60).default("") }))
    .min(2)
    .max(5),
  connect: z.boolean().default(false),
  wordBank: z.array(text(24)).max(16).default([]),
  starters: z.array(z.string().trim().max(40)).max(5).default([]),
});

// Find and fix the mistakes in a short sentence ("the cat are big" → "The cat is big.").
export const editAndCorrectContentSchema = z.object({
  text: text(200),
  focus: z.array(z.enum(["capitalization", "punctuation", "spelling", "grammar", "spacing"])).min(1).max(4),
  emoji: z.string().max(16).optional(),
  hint: z.string().trim().max(160).optional(),
});

// A sound unit a child can tap to hear (a grapheme segment, or a phoneme).
const soundUnitSchema = z.object({
  grapheme: text(6),
  sayAs: z.string().trim().max(40),
});

// Blending: tap each sound, blend them (slow or normal), then choose the word they make.
// The word itself is only spoken after answering.
export const blendSoundsContentSchema = z.object({
  emoji: z.string().max(16).optional(),
  units: z.array(soundUnitSchema).min(1).max(8),
  options: z.array(choiceOptionSchema).min(2).max(4),
});

// Segmenting: hear a word, say how many sounds it has, then pick those sounds in order.
// Sound cards are phonemes (shown as /sh/), never the word's letters.
export const segmentWordContentSchema = z.object({
  word: text(40),
  emoji: z.string().max(16).optional(),
  speech: text(60),
  sounds: z
    .array(z.object({ id: itemId, label: text(8), sayAs: text(40) }))
    .min(2)
    .max(10),
  maxCount: z.number().int().min(2).max(8),
});

// Find the pattern (e.g. the digraph) in a written word by tapping its letters.
export const findPatternContentSchema = z.object({
  word: z.string().trim().regex(/^[a-z']{2,20}$/),
  emoji: z.string().max(16).optional(),
  speech: z.string().trim().max(60).optional(),
  // What to look for, as shown to the child ("sh").
  target: text(8),
});

export const acceptedAnswerSchema = z.object({
  accepted: z.array(text(120)).min(1).max(10),
});

export const sentenceAnswerSchema = acceptedAnswerSchema.extend({
  accepted: z.array(text(200)).min(1).max(5),
  requirePunctuation: z.boolean().default(false),
});

export const sequenceAnswerSchema = z.object({
  acceptedSequences: z
    .array(z.array(text(24)).min(1).max(14))
    .min(1)
    .max(5),
});

export const pairsAnswerSchema = z.object({
  pairs: z.array(z.tuple([itemId, itemId])).min(1).max(10),
});

// Handwriting: optional per-question completion threshold (the glyph's and the level's
// otherwise). Nothing about it is secret; it is an answer so the question is scored.
export const traceAnswerSchema = z.object({
  trace: z.literal(true),
  completion: z.number().min(0.3).max(0.98).optional(),
});

// Typed writing. Closed tasks list the accepted answers; open-ended ones carry their
// rubric (compiled by the importer from writing_rubrics and the question's own required
// ideas). Server-only, like every answer.
export const writingRubricSchema = z.object({
  code: z.string().regex(/^[a-z0-9-]{2,80}$/),
  criteria: rubricCriteriaSchema,
});
export const sentenceWritingAnswerSchema = z.union([
  z.object({ accepted: z.array(text(200)).min(1).max(10) }).strict(),
  z.object({ rubric: writingRubricSchema }).strict(),
]);
export const guidedWritingAnswerSchema = z.object({ rubric: writingRubricSchema }).strict();
export const storyOrderWritingAnswerSchema = z
  .object({
    acceptedSequences: z.array(z.array(z.string().regex(/^[a-z0-9-]{1,40}$/)).min(2).max(5)).min(1).max(3),
    eventCriteria: z.record(z.string().regex(/^[a-z0-9-]{1,40}$/), rubricCriteriaSchema),
    rubric: writingRubricSchema,
  })
  .strict();
export const editAnswerSchema = z.object({ accepted: z.array(text(200)).min(1).max(5) }).strict();

// Select-all: every right option id (order does not matter).
export const selectAllAnswerSchema = z.object({
  correct: z.array(z.string().regex(/^[a-z0-9-]{1,40}$/)).min(2).max(5),
});

export const valueResponseSchema = z.object({ value: z.string().max(200) });
export const sequenceResponseSchema = z.object({ sequence: z.array(z.string().max(40)).max(20) });
export const pairsResponseSchema = z.object({
  pairs: z.array(z.tuple([z.string().max(40), z.string().max(40)])).max(10),
});
// Kept so answers queued by an older app (tracing scored on the device) still parse; the
// server rejects them, since a coverage number from the device cannot be checked.
export const coverageResponseSchema = z.object({ coverage: z.number().min(0).max(100) });
// Handwriting: the strokes as drawn (tracing.ts). `typed`: the keyboard alternative for a
// child who cannot draw (the letter typed instead; recorded as such).
export const strokesResponseSchema = z.object({
  strokes: traceStrokesSchema,
  typed: z.string().trim().min(1).max(4).optional(),
});
// Several boxes of writing (guided frames, paragraph parts, story sentences) and, for story
// writing, the order the pictures were put in (`order`, event ids).
export const linesResponseSchema = z.object({
  lines: z.array(z.string().max(600)).min(1).max(10),
  order: z.array(z.string().max(40)).max(10).optional(),
});
// Most specific shapes first: z.union keeps the first match and drops unknown keys.
export const responseSchema = z.union([
  strokesResponseSchema,
  linesResponseSchema,
  valueResponseSchema,
  sequenceResponseSchema,
  pairsResponseSchema,
  coverageResponseSchema,
]);
export type QuestionResponse = z.infer<typeof responseSchema>;

// Each type's content schema, answer schema (null = unscored) and response schema.
export const questionTypeSchemas = {
  INTRO: { content: introContentSchema, answer: null, response: null },
  MULTIPLE_CHOICE: {
    content: choiceContentSchema,
    answer: acceptedAnswerSchema,
    response: valueResponseSchema,
  },
  LISTEN_AND_CHOOSE: {
    content: choiceContentSchema,
    answer: acceptedAnswerSchema,
    response: valueResponseSchema,
  },
  PICTURE_MATCH: {
    content: choiceContentSchema,
    answer: acceptedAnswerSchema,
    response: valueResponseSchema,
  },
  MISSING_LETTER: {
    content: missingLetterContentSchema,
    answer: acceptedAnswerSchema,
    response: valueResponseSchema,
  },
  WORD_BUILDER: {
    content: wordBuilderContentSchema,
    answer: acceptedAnswerSchema,
    response: sequenceResponseSchema,
  },
  SENTENCE_BUILDER: {
    content: sentenceBuilderContentSchema,
    answer: sequenceAnswerSchema,
    response: sequenceResponseSchema,
  },
  SPELLING: { content: spellingContentSchema, answer: acceptedAnswerSchema, response: valueResponseSchema },
  MATCH: { content: matchContentSchema, answer: pairsAnswerSchema, response: pairsResponseSchema },
  SORT: { content: sortContentSchema, answer: pairsAnswerSchema, response: pairsResponseSchema },
  DRAG_DROP: {
    content: dragDropContentSchema,
    answer: sequenceAnswerSchema,
    response: sequenceResponseSchema,
  },
  READING: { content: readingContentSchema, answer: acceptedAnswerSchema, response: valueResponseSchema },
  WRITING: { content: writingContentSchema, answer: acceptedAnswerSchema, response: valueResponseSchema },
  TRACING: { content: tracingContentSchema, answer: traceAnswerSchema, response: strokesResponseSchema },
  BLEND_SOUNDS: {
    content: blendSoundsContentSchema,
    answer: acceptedAnswerSchema,
    response: valueResponseSchema,
  },
  SEGMENT_WORD: {
    content: segmentWordContentSchema,
    answer: sequenceAnswerSchema,
    response: sequenceResponseSchema,
  },
  // The answer is the letters' span in the word: "start-end" (0-based, inclusive).
  FIND_PATTERN: {
    content: findPatternContentSchema,
    answer: acceptedAnswerSchema,
    response: valueResponseSchema,
  },
  SENTENCE_DICTATION: {
    content: sentenceDictationContentSchema,
    answer: sentenceAnswerSchema,
    response: valueResponseSchema,
  },
  READ_PASSAGE: { content: readPassageContentSchema, answer: null, response: null },
  // The response is the chosen option ids (`sequence`, any order).
  SELECT_ALL: { content: selectAllContentSchema, answer: selectAllAnswerSchema, response: sequenceResponseSchema },
  ORDER_EVENTS: {
    content: orderEventsContentSchema,
    answer: sequenceAnswerSchema,
    response: sequenceResponseSchema,
  },
  SENTENCE_WRITING: {
    content: sentenceWritingContentSchema,
    answer: sentenceWritingAnswerSchema,
    response: valueResponseSchema,
  },
  GUIDED_WRITING: { content: guidedWritingContentSchema, answer: guidedWritingAnswerSchema, response: linesResponseSchema },
  STORY_ORDER_WRITING: {
    content: storyOrderWritingContentSchema,
    answer: storyOrderWritingAnswerSchema,
    response: linesResponseSchema,
  },
  EDIT_AND_CORRECT: { content: editAndCorrectContentSchema, answer: editAnswerSchema, response: valueResponseSchema },
} as const;

export type SupportedQuestionType = keyof typeof questionTypeSchemas;

export function isSupportedQuestionType(type: string): type is SupportedQuestionType {
  return Object.hasOwn(questionTypeSchemas, type);
}

